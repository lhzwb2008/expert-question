CASH_OCT = 119650000.00
BASE, EXE = "2026-09-30", "2026-10-01"
OLD_BPS, OLD_MIN = 0.0003, 5.00      # 旧佣金：成交金额 3 个基点，每笔不低于 5 美元
NEW_PS, NEW_MIN = 0.005, 1.00        # 新佣金：每股 0.005 美元，每条不低于 1 美元（2026-11-01 起）
r2 = lambda x: round(x + 1e-9, 2)

RECS, PX = {}, {}
for t in ETF:
    RECS[t], PX[t] = load_mcp_prices(RAW / f"{t}.json", 0)


def px(t, day, col="Close"):
    return float(PX[t].loc[day, col])


def oct_trades():
    out = []
    for t in OCT:
        q = OCT[t] - SEP[t]
        if not q:
            continue
        side = "买入" if q > 0 else "卖出"
        prev = round(px(t, BASE), 2)
        lim = round(prev * (1.01 if q > 0 else 0.99), 2)
        o, h, lo, c = (px(t, EXE, k) for k in ("Open", "High", "Low", "Close"))
        avg = round((o + h + lo + c) / 4, 4)
        assert lo <= avg <= h and (avg <= lim if q > 0 else avg >= lim), (t, avg, lim)
        amt = r2(abs(q) * avg)
        comm = max(OLD_MIN, r2(amt * OLD_BPS))
        out.append(dict(t=t, side=side, q=abs(q), prev=prev, lim=lim, avg=avg, amt=amt, comm=comm,
                        slip=(avg / prev - 1) * (1 if q > 0 else -1), new_comm=max(NEW_MIN, r2(abs(q) * NEW_PS))))
    return out


def adv(t, n, end=BASE):
    v = PX[t][PX[t].index <= end].Volume.tail(n)
    assert len(v) == n and v.index[-1] == end
    return float(v.mean()), v.index[0]


