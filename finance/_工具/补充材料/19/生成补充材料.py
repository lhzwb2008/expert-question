def month_table():
    """2022-09 至 2026-09 各月的月末收盘、月内最高最低收盘、月成交额和月涨跌幅（不复权）。"""
    rows = []
    for code in ("510500", "512100", "000905", "000852"):
        df = C.px(code)
        df = df[df.index <= "2026-09-30"].copy()
        df["ym"] = df.index.str[:7]
        prev = None
        for ym, g in df.groupby("ym"):
            last = g.iloc[-1]
            chg = "" if prev is None else f"{(last.close / prev - 1) * 100:.2f}"
            unit = 1e8
            rows.append([ym, g.index[-1], code, NAME[code], f"{last.close:.3f}" if code.startswith("51") else f"{last.close:.2f}",
                         f"{g.close.max():.3f}" if code.startswith("51") else f"{g.close.max():.2f}",
                         f"{g.close.min():.3f}" if code.startswith("51") else f"{g.close.min():.2f}",
                         len(g), f"{g.turnover.sum() / unit:.2f}", chg])
            prev = last.close
    rows.sort(key=lambda r: (r[0], r[2]))
    return rows


def tracking():
    """2025-09 至 2026-09：ETF 复权月收益和指数月收益、跟踪偏离、日均成交额。"""
    t_rows, l_rows = [], []
    for etf, idx in (("510500", "000905"), ("512100", "000852")):
        f = C.px(etf, "fwd").close
        n = C.px(etf)
        i = C.px(idx).close
        df = pd.DataFrame({"f": f, "i": i, "to": n.turnover, "vol": n.volume.astype(float)})
        df = df[(df.index >= "2025-08-01") & (df.index <= "2026-09-30")]
        df["rf"] = df.f.pct_change()
        df["ri"] = df.i.pct_change()
        df["ym"] = df.index.str[:7]
        me = df.groupby("ym").tail(1)
        for k in range(1, len(me)):
            ym = me.ym.iloc[k]
            g = df[df.ym == ym]
            re_ = me.f.iloc[k] / me.f.iloc[k - 1] - 1
            ri = me.i.iloc[k] / me.i.iloc[k - 1] - 1
            te = (g.rf - g.ri).std() * (252 ** 0.5)
            t_rows.append([ym, f"{etf} {NAME[etf]}", f"{idx} {NAME[idx]}", round(re_ * 100, 2), round(ri * 100, 2),
                           round((re_ - ri) * 100, 2), round(te * 100, 2), round((g.rf - g.ri).abs().max() * 100, 3)])
            l_rows.append([ym, f"{etf} {NAME[etf]}", len(g), round(g.to.mean() / 1e8, 2), round(g.to.min() / 1e8, 2),
                           round(g.vol.mean() / 1e4, 1), g.to.idxmin()])
    return t_rows, l_rows


def nominal(start: str, k: int) -> str:
    y0, m0, d0 = map(int, start.split("-"))
    y, m = y0 + (m0 - 1 + k) // 12, (m0 - 1 + k) % 12 + 1
    return f"{y:04d}-{m:02d}-{min(d0, calendar.monthrange(y, m)[1]):02d}"


