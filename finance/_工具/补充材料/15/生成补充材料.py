def b03():
    pre = G14.pre_research()
    hold = [(r["code"], r["name"], r["sh"]) for r in pre["rows"]]
    lp = {}
    for c, _, _ in hold:
        lp[c] = {r["date"]: F(r["close"]) for r in json.load(open(G14.LP / f"{c}_noadj.json", encoding="utf-8"))}
    mv_rows = [[c, n, sh, float(lp[c][TRIAL_DAY]), round(float(sh * lp[c][TRIAL_DAY]), 2)] for c, n, sh in hold]
    mv = sum(sh * lp[c][TRIAL_DAY] for c, _, sh in hold)
    wt = {c: sh * lp[c][TRIAL_DAY] / mv for c, _, sh in hold}
    px = pd.DataFrame({c: mcp_df(DATA / "港股红利" / f"{c}.json").Close for c, _, _ in hold}).sort_index()
    px = px[px.index <= TRIAL_DAY].dropna()
    h = hsi().Close.round(2)
    px = px[px.index.isin(h.index)]
    p = px.tail(251)
    ret = p.pct_change().iloc[1:]
    rp = sum(ret[c] * float(wt[c]) for c in wt)
    rm = h.reindex(p.index).pct_change().iloc[1:]
    assert len(rp) == 250 and not rm.isna().any()
    b = rp.cov(rm) / rm.var()
    idx = F(f"{h[TRIAL_DAY]:.2f}")
    tgt = F(1, 2) * F(b) * mv / (idx * 50)
    big = math.floor(tgt)
    mini = math.floor((tgt - big) * 5)  # 旧口径：小型恒指向下取整
    big_m, mini_m = margin_on(TRIAL_DAY)
    notional = (big * 50 + mini * 10) * idx
    margin = big * big_m + mini * mini_m
    stress = notional * F(20, 100)  # 旧口径：固定20%
    cash = pre["cash"]
    days = [[d, round(float(rp[d]), 8), round(float(rm[d]), 8)] for d in rp.index]
    summ = [["试算日", TRIAL_DAY], ["持仓来源", "立项预研建仓测算底稿（2026-04-30）的12只观察名单和股数，假设成立后不调仓"],
            ["股票市值(港元)", round(float(mv), 2)], ["现金(港元，沿用预研)", round(float(cash), 2)],
            ["恒指收盘", float(idx)], ["Beta窗口", "250个交易日（旧口径只用一个窗口）"],
            ["样本起止", f"{rp.index[0]} 至 {rp.index[-1]}"], ["Beta", round(float(b), 4)],
            ["对冲比例", "50%"], ["目标张数", round(float(tgt), 4)], ["恒指期货(张)", big], ["小型恒指期货(张，向下取整)", mini],
            ["对冲名义(港元)", round(float(notional), 2)], ["适用保证金(港元/张)", f"恒指 {big_m:,}，小型 {mini_m:,}"],
            ["初始保证金合计(港元)", round(float(margin), 2)], ["压力追加(港元，名义×20%)", round(float(stress), 2)],
            ["保证金储备(港元)", round(float(margin + stress), 2)],
            ["现金是否够用（旧口径：全部现金可用）", "够用" if margin + stress <= cash else "不够"]]
    write_xlsx(
        HERE / f"{P}B03_立项预研对冲试算底稿_20260630.xlsx",
        [("预研持仓", ["代码", "名称", "股数", f"{TRIAL_DAY}收盘价(港元)", "市值(港元)"], mv_rows),
         ("组合日收益", ["交易日", "组合日收益", "恒生指数日收益"], days),
         ("试算结果", ["项目", "数值"], summ)],
        notes={
            "预研持仓": ["收盘价为不复权收盘价。权重 = 试算日市值占比，回看期间固定。"],
            "组合日收益": ["个股日收益用前复权收盘价（Yahoo Finance 日线 Close 列），恒指用 ^HSI 收盘价保留2位小数；日期都已换成香港交易日。"],
            "试算结果": ["本底稿按2026-06立项预研时的旧口径试算：只用250日Beta；小型恒指向下取整；压力追加按名义的固定20%；全部现金可用于保证金。",
                     "（2026-10-23 对冲口径定稿后由风控补注）上述做法已被定稿的对冲口径和保证金储备规则替代，本底稿只说明预研时的判断过程，不作为正式测算的依据。"],
        },
    )
