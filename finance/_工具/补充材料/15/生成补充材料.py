def raw_close(d: pd.DataFrame) -> pd.Series:
    """Yahoo 的 Close 已按分红前复权（除息日前乘 1 − D/除息前一日收盘）；倒推出不复权收盘价。"""
    adj = d.Close.astype(float)
    div = d.Dividends.astype(float)
    days = list(adj.index)
    out, factor = {}, 1.0
    for i in range(len(days) - 1, -1, -1):
        day = days[i]
        out[day] = adj[day] / factor
