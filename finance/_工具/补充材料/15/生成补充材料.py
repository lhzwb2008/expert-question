def roll_beta(px: pd.DataFrame, col: str, day: str, n: int):
    p = px[px.index <= day][[col, "HSI"]].tail(n + 1)
    if len(p) < n + 1:
        return None
    r = p.pct_change().iloc[1:]
    return r[col].cov(r.HSI) / r.HSI.var()
def month_ends(idx, start, end):
    s = pd.Series(idx, index=idx)
    s = s[(s >= start) & (s <= end)]
    return list(s.groupby(s.str[:7]).max())
def ltd_table(days: list[str]):
    """恒指期货最后交易日 = 合约月份最后一个营业日之前的一个营业日。营业日按恒指有收盘的日子算。"""
    s = pd.Series(days, index=days)
    out = {}
    for m, g in s.groupby(s.str[:7]):
        out[m] = (g.iloc[-1], g.iloc[-2])
    return out
