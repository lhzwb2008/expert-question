"""12 题补充材料的各份文件（B01 至 B16），由 生成补充材料.py 调用。"""
from __future__ import annotations

import csv
import math
from decimal import Decimal as D


def write_all(m, out, g):
    P, CODES, NAME, H0, YD, NC = g["P"], g["CODES"], g["NAME"], g["H0"], g["YD"], g["NC"]
    write_xlsx, write_docx, fl, pct, money = g["write_xlsx"], g["write_docx"], g["fl"], g["pct"], g["money"]
    px, td, days, vol, close = m["px"], m["td"], m["days"], m["vol"], m["close"]
    LOT = {"0700.HK": 100, "9988.HK": 100, "0941.HK": 500, "1299.HK": 200, "2318.HK": 500, "0883.HK": 1000, "0388.HK": 100, "6990.HK": 100,
           "1952.HK": 500, "9969.HK": 1000, "9626.HK": 20, "3896.HK": 2000}
    hold = lambda d: H0 if d == "2026-06-30" else m["hold_on"][d]

    def nav(d):
        mv = {c: hold(d)[c] * px(d, c) for c in CODES}
        return mv, sum(mv.values()) + m["cash_on"][d]

    def old_measure(d, h):
        """2026 年 6 月版口径：ADV60、20% 参与率、按每手向下取整。"""
        upto = [x for x in days if x <= d]
        res = {}
        for c in CODES:
            v = [int(vol.loc[x, c]) for x in upto[-60:]]
            adv = sum(v) / 60
            cap = int(adv * 0.2 // LOT[c]) * LOT[c]
            res[c] = dict(adv=adv, cap=cap, days=math.ceil(h[c] / cap) if h[c] else 0)
        return res

    # ---------- B01 月末持仓快照 ----------
    month_ends = ["2026-06-30", "2026-07-31", "2026-08-31", "2026-09-30"]
    sheets, summ, flows = [], [], []
    prev = None
    for d in month_ends:
        mv, nv = nav(d)
        rows = [[c, NAME[c], hold(d)[c], fl(px(d, c)), round(fl(mv[c]), 2), round(fl(mv[c] / nv) * 100, 3)] for c in CODES]
        rows.append(["现金", "现金、应收股利及待交收款", "", "", round(fl(m["cash_on"][d]), 2), round(fl(m["cash_on"][d] / nv) * 100, 3)])
        rows.append(["合计", "产品资产净值", "", "", round(fl(nv), 2), 100.0])
        sheets.append((d, ["代码", "名称", "持股数", "收盘价(港元)", "市值(港元)", "占资产净值(%)"], rows))
        top = sorted(CODES, key=lambda c: -mv[c])[:3]
        summ.append([d, round(fl(sum(mv.values())), 2), round(fl(m["cash_on"][d]), 2), round(fl(nv), 2), "、".join(NAME[c] for c in top),
                     round(fl(sum(mv[c] for c in top) / nv) * 100, 3)])
        if prev:
            seg = [t for t in m["trades"] if prev < t["day"] <= d]
            dv = sum((v["amount"] for v in m["divs"] if prev < v["day"] <= d), D(0))
            sub = D("31500000.00") if prev < "2026-09-30" <= d else D(0)
            flows.append([f"{prev} 至 {d}", round(fl(m["cash_on"][prev]), 2), round(fl(sum((t["net"] for t in seg if t["side"] < 0), D(0))), 2),
                          round(fl(sum((t["net"] for t in seg if t["side"] > 0), D(0))), 2), round(fl(dv), 2), round(fl(sub), 2), round(fl(m["cash_on"][d]), 2)])
        prev = d
    sheets.append(("月末汇总", ["日期", "股票市值(港元)", "现金及应收(港元)", "资产净值(港元)", "市值前三的股票", "前三合计占比(%)"], summ))
    sheets.append(("现金变动", ["期间", "期初(港元)", "卖出净收入(港元)", "买入净支出(港元)", "应收股利(港元)", "开放日申购款(港元)", "期末(港元)"], flows))
    write_xlsx(out / f"{P}B01_持仓月末快照_2026年6至9月.xlsx", sheets,
               {"月末汇总": ["估值系统月末导出。收盘价为当日不复权收盘价，单位港元。现金一行含应收股利和已成交未交收的款项。",
                         "股利按除净日计入应收；成交按成交日记账，交收日见《港股流动性_B02》。9 月 30 日开放日的赎回款 10 月 8 日划出，不在 9 月末现金里扣除。"],
                "现金变动": ["买入净支出为负数。费用已从成交金额里扣除。"]},
               formats={s[0]: {"收盘价(港元)": "0.000", "市值(港元)": "#,##0.00", "占资产净值(%)": "0.000"} for s in sheets[:4]})

    # ---------- B02 持仓变动成交明细 ----------
    with open(out / f"{P}B02_持仓变动成交明细_2026年8至10月.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["成交日", "交收日", "事由", "代码", "名称", "方向", "成交股数", "成交价(港元)", "成交金额(港元)", "佣金", "印花税", "交易费", "证监会交易征费", "会财局交易征费",
                    "清算金额(港元)", "成交时段"])
        for t in m["trades"]:
            w.writerow([t["day"], t["settle"], t["tag"], t["code"], NAME[t["code"]], "买入" if t["side"] > 0 else "卖出", t["n"], f"{t['price']:.3f}", f"{t['amount']:.2f}",
                        f"{t['comm']:.2f}", f"{t['stamp']:.2f}", f"{t['tf']:.2f}", f"{t['sfc']:.2f}", f"{t['afrc']:.2f}", f"{t['net']:.2f}", "收市竞价"])
    nc = [t for t in m["trades"] if t["code"] == NC]
    yd = [t for t in m["trades"] if t["code"] == YD]
    rs = [t for t in m["trades"] if t["tag"] == "开放日赎回变现"]

    # ---------- B03 9 月 30 日开放日赎回处置记录 ----------
    d23 = "2026-09-23"
    mv23, nv23 = nav(d23)
    mv02, nv02 = nav("2026-10-02")
    keep = nv23 * D("0.01")
    red_est = D("80000000") * (nv23 / D("2236800000"))
    yd_left = sum(t["n"] for t in m["trades"] if t["code"] == YD and t["day"] > d23) * px(d23, YD)
    need_est = red_est + yd_left + keep - m["cash_on"][d23] - D("31500000")
    rs_sum = sum(t["amount"] for t in rs)
    o = old_measure(d23, hold(d23))
    up = lambda c: f"{NAME[c]}由 {pct(mv23[c] / nv23)} 变为 {pct(mv02[c] / nv02)}"
    b03 = f"""# 2026 年 9 月 30 日开放日赎回处置记录

形成时间：2026-10-09
记录：周宁（产品部）；何岚（投资经理）、赵衡（交易部）、林知远（风控部）确认
用途：记录本产品 2026 年三季度开放日的赎回处置过程，供开放频率评估和口径修订参考。

## 一、开放日安排

本产品每季度最后一个交易日开放申购赎回，赎回采用提前预约：投资者须在开放日前五个交易日的 15:00 之前提交预约，开放日按当日单位净值确认，赎回款在开放日后五个工作日内划出。

本季开放日为 2026-09-30，预约截止 2026-09-23 15:00。

## 二、预约结果

- 预约赎回 80,000,000 份，占开放日前总份额 2,236,800,000 份的 {pct(D('80000000') / D('2236800000'))}。其中最大的一笔来自一家银行理财子公司，40,000,000 份。
- 预约申购 31,500,000 港元，开放日到账。
- 按 9 月 23 日收盘的资产净值 {money(nv23)} 港元估算，赎回金额约 {money(red_est)} 港元。

## 三、处置方案（9 月 24 日确定）

当时适用 2026 年 6 月版《港股组合流动性测算口径》（《港股流动性_B04》）。该口径下赎回按「先用现金、再按流动性从好到差卖出」应对，现金保留 1% 的资产净值作为日常留存。

9 月 23 日现金及应收 {money(m['cash_on'][d23])} 港元，加上开放日到账的申购款 31,500,000 港元，扣除留存 {money(keep)} 港元和云顶新耀剩余买入计划约 {money(yd_left)} 港元（按 9 月 23 日收盘价估），投资经理估计需卖出约 {fl(need_est) / 1e4:,.0f} 万港元。按 6 月版口径，变现天数为 1 天、市值较大的股票优先，选定腾讯控股、阿里巴巴-W、友邦保险三只，9 月 28 日至 10 月 2 日四个交易日在收市竞价时段卖出：

- 腾讯控股卖出 {sum(t['n'] for t in rs if t['code'] == '0700.HK'):,} 股；
- 阿里巴巴-W 卖出 {sum(t['n'] for t in rs if t['code'] == '9988.HK'):,} 股；
- 友邦保险卖出 {sum(t['n'] for t in rs if t['code'] == '1299.HK'):,} 股。

合计成交金额 {money(rs_sum)} 港元，逐笔明细见《港股流动性_B02》。10 月 1 日香港休市。

## 四、确认和划款

9 月 30 日单位净值 {m['unit']} 港元。赎回确认金额 {money(m['red_amt'])} 港元，10 月 8 日划出；申购确认 {money(m['sub_units'])} 份。

## 五、处置后的问题

1. 只卖流动性好的股票，组合结构被动变化：处置前后（9 月 23 日与 10 月 2 日）占资产净值的比例，{up('0700.HK')}，{up('9988.HK')}，{up('1299.HK')}；{up(YD)}（同期还在加仓），{up('6990.HK')}。好卖的股票占比下降、难卖的上升，下一次赎回时可用的好卖的股票变少。
2. 6 月版口径的变现天数按 ADV60 和 20% 参与率算。9 月 23 日按这一口径，云顶新耀变现天数 {o[YD]['days']} 天、诺诚健华 {o[NC]['days']} 天、科伦博泰生物-B {o['6990.HK']['days']} 天，但赎回测算只看组合合计能卖多少，看不出这些股票会越积越重。
3. 云顶新耀当时还在按计划加仓（9 月 14 日起每天 31.4 万股），处置期间没有暂停，加仓和赎回卖出同时进行。

## 六、后续

- 风控部在修订口径时把赎回情景改为每只股票按同样比例卖出（已写进 2026 年 10 月版 A03）。
- 产品部按新口径的测算结果，在评审会上提出开放频率的调整方案。
- 本记录只描述 9 月 30 日开放日的处置，不作为新口径下的测算依据。
"""
    (out / f"{P}B03_2026年9月30日开放日赎回处置记录.md").write_text(b03, encoding="utf-8")

    # ---------- B04 2026 年 6 月版口径（已废止） ----------
    b04 = """# 港股组合流动性测算口径（2026 年 6 月版）

文件状态：已废止。2026-10-27 风控委员会通过 2026 年 10 月版口径后废止，被《港股流动性_A03_流动性口径》《港股流动性_A04_定档规则与交付》替代。只用于查阅 2026 年二、三季度的流动性测算和 9 月 30 日开放日的赎回处置，不作为开放频率评估的依据。
制定：风控部，2026-06-15 发布。

## 一、用途

每季度末测算产品持仓的变现能力，写进季度流动性风险报告；开放日遇到赎回时，按本口径安排卖出。

## 二、日均成交量

只用 ADV60：基准日和它之前一共 60 个交易日的日成交量算术平均，每只股票用自己的交易日。

## 三、日可变现量和变现天数

- 日可变现量 = ADV60 × 20%，向下取整到每手股数的整数倍。
- 变现天数 = 持股数 ÷ 日可变现量，向上取整。
- N 日可变现市值：每只股票取持股数和 N × 日可变现量里较小的一个，乘以基准日收盘价后相加。N 取 1、2、3、5、10。
- N 日可变现比例 = N 日可变现市值 ÷ 股票总市值。

## 四、流动性评级

按 5 日可变现比例评级：70% 及以上为「良好」，50% 至 70% 为「关注」，50% 以下为「不足」。

## 五、赎回应对

赎回金额先用现金支付，现金保留资产净值的 1% 不动用。现金不足的部分，按变现天数从短到长、变现天数相同时按市值从大到小的顺序卖出，直到凑够金额。所需天数为凑够金额需要的最少交易日数。

季度报告里列 10%、20%、30% 三档赎回的所需天数，只作参考。

## 六、与 2026 年 10 月版的主要差异

| 项目 | 6 月版（本文件） | 10 月版（A03、A04） |
| --- | --- | --- |
| 日均成交量 | ADV60 | ADV20 和 ADV60 取较小 |
| 参与率 | 20% | 25% |
| 取整 | 按每手向下取整 | 按 1 股向下取整，不考虑每手 |
| 分母 | 股票总市值 | 同左（十二只股票市值之和，不含现金） |
| 赎回情景 | 先用现金，再按流动性从好到差卖出 | 不用现金，每只股票按赎回比例卖出同样的比例 |
| 赎回档位 | 10%、20%、30% | 10%、20%、30%、50% |
| 用途 | 季度报告、开放日处置 | 开放频率定档，按 30% 情景 |

上表是 10 月修订时补在本文件后面的对照，以 10 月版原文为准。
"""
    (out / f"{P}B04_流动性测算口径2026年6月版（已废止）.md").write_text(b04, encoding="utf-8")

    # ---------- B05 二季度末流动性测算底稿（6 月版口径） ----------
    d0 = "2026-06-30"
    o0 = old_measure(d0, H0)
    mv0, nv0 = nav(d0)
    tot0 = sum(mv0.values())
    r5 = [[c, NAME[c], H0[c], fl(px(d0, c)), round(fl(mv0[c]), 2), round(o0[c]["adv"], 2), LOT[c], o0[c]["cap"], o0[c]["days"]] for c in CODES]
    lad = []
    for n in (1, 2, 3, 5, 10):
        v = sum(min(H0[c], n * o0[c]["cap"]) * px(d0, c) for c in CODES)
        lad.append([n, round(fl(v), 2), round(fl(v / tot0) * 100, 2)])
    lad5 = next(r for r in lad if r[0] == 5)[2]
    grade = "良好" if lad5 >= 70 else ("关注" if lad5 >= 50 else "不足")
    cash_use = m["cash_on"][d0] - nv0 * D("0.01")
    wf = []
    for x in (D("0.1"), D("0.2"), D("0.3")):
        need = nv0 * x - cash_use
        n = next(n for n in range(1, 30) if sum(min(H0[c], n * o0[c]["cap"]) * px(d0, c) for c in CODES) >= need)
        wf.append([f"{int(x * 100)}%", round(fl(nv0 * x), 2), round(fl(cash_use), 2), round(fl(need), 2), n])
    write_xlsx(out / f"{P}B05_二季度末流动性测算底稿_20260630（6月版口径）.xlsx",
               [("持仓变现能力", ["代码", "名称", "持股数", "收盘价(港元)", "市值(港元)", "ADV60(股)", "每手股数", "日可变现量(股)", "变现天数"], r5),
                ("变现阶梯", ["N（交易日）", "N日可变现市值(港元)", "N日可变现比例(%)"], lad),
                ("赎回应对", ["赎回比例", "赎回金额(港元)", "可动用现金(港元)", "需卖出(港元)", "所需天数"], wf),
                ("评级", ["项目", "内容"], [["基准日", d0], ["口径", "2026 年 6 月版（已废止）"], ["股票总市值(港元)", money(tot0)], ["资产净值(港元)", money(nv0)],
                                         ["5 日可变现比例", f"{lad5:.2f}%"], ["评级", grade], ["编制", "林知远（风控部），2026-07-03"],
                                         ["用途", "2026 年二季度流动性风险报告附表"]])],
               {"持仓变现能力": ["ADV60 为 6 月 30 日及之前 60 个交易日的算术平均；日可变现量 = ADV60 × 20%，按每手向下取整。"],
                "赎回应对": ["按 6 月版口径：现金先用，保留资产净值的 1%；不足部分按流动性从好到差卖出。所需天数是凑够金额的最少交易日数。"]},
               formats={"持仓变现能力": {"收盘价(港元)": "0.000", "市值(港元)": "#,##0.00", "ADV60(股)": "#,##0.00"},
                        "变现阶梯": {"N日可变现市值(港元)": "#,##0.00", "N日可变现比例(%)": "0.00"},
                        "赎回应对": {"赎回金额(港元)": "#,##0.00", "可动用现金(港元)": "#,##0.00", "需卖出(港元)": "#,##0.00"}})

    # ---------- B06 开放频率调整讨论纪要 ----------
    b06 = [
        ("会议信息", ["时间：2026-09-18 10:00—11:30。地点：产品部会议室。主持：产品委员会召集人。",
                   "出席：周宁（产品部）、何岚（投资经理）、林知远（风控部）、赵衡（交易部）、孙沛（合规部）、渠道部代表。记录：周宁。",
                   "议题：本产品由每季度开放调整为更高开放频率的可行性。"]),
        ("一、产品部汇报", [
            "本产品 2024 年 12 月成立，2025 年 3 月起每季度最后一个交易日开放。成立以来六次开放日的赎回比例在 1.8% 至 5.6% 之间，最高一次是 2026 年 3 月 31 日（明细见《港股流动性_B14》）。",
            "渠道部反馈：同类港股权益产品多为每日或每周开放，季度开放影响新增资金的认购意愿，两家代销银行提出希望至少每月开放。",
            "产品部提出三个方案供讨论：每日开放、每周开放（每周最后一个交易日）、每月开放（每月最后一个交易日）。",
        ]),
        ("二、讨论", [
            "风控部：开放频率越高，对持仓变现能力的要求越高。现行 6 月版口径是为季度报告写的，只看组合合计能卖多少，用于定开放频率不够。建议另定测算口径：单只股票按近期成交量算可变现量，赎回按每只股票同比例卖出，并设定一个压力情景作为定档依据。",
            "投资经理：组合里有几只市值较大但成交量不大的股票，云顶新耀在 9 月中旬开始按计划加仓，诺诚健华 8 月以来在减持。开放频率定下来以后，投资经理会据此安排仓位。",
            "交易部：港股收市竞价时段能承接一定量的卖单，但小盘股的成交量波动大，近期和过去两三个月的成交量可能差得较多，测算时不宜只看一个窗口。",
            "合规部：调整开放频率需修改产品合同和招募说明书，并履行持有人告知程序，从决定到生效至少需要一个月。",
            "渠道部：投资者结构以银行理财和机构为主，前十大持有人合计约四成，单一持有人的大额赎回是主要压力来源。",
        ]),
        ("三、会议结论", [
            "1. 风控部牵头修订流动性测算口径，并起草开放频率的定档规则，10 月底前报风控委员会审批。",
            "2. 测算基准日定为 2026-10-30，产品部根据测算结果提出开放频率方案，报产品委员会决定。",
            "3. 9 月 30 日开放日仍按现行 6 月版口径处置。",
            "4. 会议不对开放频率作结论。",
        ]),
    ]
    write_docx(out / f"{P}B06_开放频率调整讨论纪要_20260918.docx", "港股组合产品开放频率调整讨论纪要", b06)

