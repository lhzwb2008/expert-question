# ---------------- B08 立项预研建仓测算底稿 ----------------
PRE_DAY = "2026-04-29"
PRE_WIN0 = "2025-04-29"
PRE_BASKET = ["0941.HK", "0762.HK", "0939.HK", "3988.HK", "1288.HK", "0883.HK", "0857.HK", "0386.HK", "1088.HK", "0006.HK",
              "0016.HK", "1919.HK"]
PRE_RMB = F(500_000_000)
PRE_STOCK = F(90, 100)
PRE_SCAP, PRE_ICAP = F(10, 100), F(30, 100)
PRE_FEE = F(1, 100) + F(2, 1000)
PRE_TIERS = (F(45, 1000), F(50, 1000), F(55, 1000))


def pre_research():
    fx = next(r for r in fx_rows() if r["day"] == PRE_DAY)
    rate = F(f"{fx['close']:.6f}")
    sel = []
    for c in PRE_BASKET:
        dv = dividends(c)
        assert not any(d == PRE_WIN0 for d, _ in dv), c
        ttm = sum((v for d, v in dv if PRE_WIN0 < d <= PRE_DAY), F(0))
        cl = close_on(c, PRE_DAY)
        sel.append(dict(code=c, name=name(c), ind=IND[c], lot=INFO[c]["lot_size"], close=cl, ttm=ttm, y=ttm / cl))
    tot = sum(r["y"] for r in sel)
    w0 = {r["code"]: r["y"] / tot for r in sel}
    w = dict(w0)
    flag = {c: "" for c in w}
    # 预研假设：先处理行业，再处理单只，超出部分等权分给未触及上限的股票，只处理一轮
    for k in sorted({r["ind"] for r in sel}):
        s = sum(w[r["code"]] for r in sel if r["ind"] == k)
        if s > PRE_ICAP:
            for r in sel:
                if r["ind"] == k:
                    w[r["code"]] *= PRE_ICAP / s
                    flag[r["code"]] = "行业上限"
    for c in w:
        if w[c] > PRE_SCAP:
            w[c] = PRE_SCAP
            flag[c] = "单只上限"
    free = [c for c in w if not flag[c]]
    rest = 1 - sum(w.values())
    for c in free:
        w[c] += rest / len(free)
    over = [c for c in w if w[c] > PRE_SCAP] + [k for k in {r["ind"] for r in sel}
                                                 if sum(w[r["code"]] for r in sel if r["ind"] == k) > PRE_ICAP]
    assets = PRE_RMB / rate
    rows = []
    for r in sel:
        tgt = assets * PRE_STOCK * w[r["code"]]
        lots = round(tgt / r["close"] / r["lot"])  # 预研时按四舍五入到整手
        sh = lots * r["lot"]
        mv = sh * r["close"]
        tr = F(10, 100) if tax_type(r["code"]) == "H股" else F(0)  # 预研时红筹股暂按 0%
        rows.append(dict(r, w0=w0[r["code"]], w=w[r["code"]], flag=flag[r["code"]], tgt=tgt, lots=lots, sh=sh, mv=mv,
                         tax="H股" if tr else ("红筹（待确认）" if r["code"] in RED else "其他"), rate=tr,
                         net=sh * r["ttm"] * (1 - tr)))
    mv = sum(x["mv"] for x in rows)
    net = sum(x["net"] for x in rows)
    ny = net / assets
    cap = ny - PRE_FEE
    ok = [t for t in PRE_TIERS if t <= cap]
    return dict(fx=fx, rate=rate, rows=rows, assets=assets, mv=mv, cash=assets - mv, net=net, ny=ny, cap=cap,
                tier=ok[-1] if ok else None, over=over, wsum=sum(w.values()))


