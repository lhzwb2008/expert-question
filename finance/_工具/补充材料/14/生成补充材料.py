def b11():
    import random
    rnd = random.Random(20261029)
    days = ["2026-10-12", "2026-10-13", "2026-10-14", "2026-10-15", "2026-10-16", "2026-10-19", "2026-10-20", "2026-10-21",
            "2026-10-22", "2026-10-23", "2026-10-26", "2026-10-27", "2026-10-28"]
    chans = [("直销柜台", "机构"), ("直销网上交易", "个人"), ("银行代销A", "个人"), ("银行代销B", "个人"), ("券商代销", "个人"),
             ("第三方销售平台", "个人")]
    raw = []
    for i, d in enumerate(days):
        boost = 4 if i == len(days) - 1 else 1  # 末日集中认购
        for ch, typ in chans:
            if typ == "个人":
                amt = rnd.randint(300, 1100) * 10000 * boost
                n = max(1, amt // rnd.randint(50000, 150000))
            else:
                amt = rnd.choice([0, 0, 2000, 3000, 5000]) * 10000 * boost
                n = 0 if amt == 0 else rnd.randint(1, 2)
            raw.append([d, ch, typ, n, F(amt)])
    before = sum(r[4] for r in raw if r[0] != days[-1])
    last = sum(r[4] for r in raw if r[0] == days[-1])
    cap = F(800_000_000)
    assert before < cap < before + last, (before, last)
    ratio = (cap - before) / last
    rows, acc = [], F(0)
    for r in raw:
        conf = r[4] if r[0] != days[-1] else F(math.floor(r[4] * ratio * 100), 100)
        rows.append(r + [conf])
        acc += conf
    lastrow = next(x for x in reversed(rows) if x[4] > 0)
    lastrow[5] += cap - acc
    assert sum(x[5] for x in rows) == cap
    with open(HERE / f"{P}B11_募集期认购流水汇总导出_20261029.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["trade_date", "channel", "investor_type", "accounts", "apply_amount_cny", "confirm_ratio", "confirm_amount_cny",
                    "status", "confirm_date"])
        for d, ch, typ, n, amt, conf in rows:
            rt = "1.00000000" if d != days[-1] else f"{float(ratio):.8f}"
            w.writerow([d, ch, typ, n, f"{float(amt):.2f}", rt if amt else "", f"{float(conf):.2f}",
                        ("有效" if d != days[-1] else "末日比例确认") if amt else "无认购", "2026-10-29"])
    return float(before), float(last), float(ratio)


