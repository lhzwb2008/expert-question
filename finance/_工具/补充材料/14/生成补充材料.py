def mcp_rows(path: Path):
    rec = json.load(open(path, encoding="utf-8"))
    return json.loads(rec["原始返回"]["content"][0]["text"])


def dividends(c):
    df = pd.DataFrame(mcp_rows(DATA / "港股红利" / f"{c}.json"))
    df["day"] = (pd.to_datetime(df.Date.str[:19]) + pd.Timedelta(hours=8)).dt.strftime("%Y-%m-%d")
    d = df[df.Dividends > 0]
    return [(a, F(f"{b:.4f}")) for a, b in zip(d.day, d.Dividends)]


def close_on(c, day):
    rows = {r["date"]: r for r in json.load(open(LP / f"{c}_noadj.json", encoding="utf-8"))}
    return F(rows[day]["close"])


def fx_rows():
    out = []
