def next_wd(d: str, lag: int) -> str:
    x = dt.date.fromisoformat(d) + dt.timedelta(days=lag)
    while x.weekday() >= 5:
        x += dt.timedelta(days=1)
    return x.isoformat()


def load_lp():
    out = {}
    for t in TS:
        rec = json.load(open(LP / f"{t}.US_noadj.json", encoding="utf-8"))
        out[t] = {x["date"]: float(x["close"]) for x in rec["返回"]}
    return out, rec["查询时间"]


def pos_at(d: str) -> dict:
    p = dict(POS0)
    if d < LRCX_BUY[0]:
        p["LRCX"] -= LRCX_BUY[1]
    return p


def hist_divs():
    """付息日在 2025-03-01 以后、除息日在 2025-10-31 以前的分红。KLAC 2026-06-12 一拆十，在线返回的拆股前分红是调小后的数，乘回 10 才是当时的实际每股。"""
    days = sorted(load_lp()[0]["AAPL"])
    out = []
    for t in TS:
        _, m = load_mcp_prices(MCP / f"{t}.json", 0)
        for d, v in m.Dividends.items():
            if v and "2025-02-11" <= d < W1 and next_wd(d, PAY_LAG[t]) >= W0:
                per = round(float(v) * (10 if t == "KLAC" else 1), 4)
                prev = days[days.index(d) - 1]
                sh = pos_at(prev)[t]
                gross = r2(sh * per)
                rate = 0.30 if (t, d) == ("LRCX", LRCX_BAD) else 0.10
                out.append(dict(t=t, ex=d, per=per, ret=float(v), sh=sh, gross=gross, tax=r2(gross * rate), rate=rate,
                                net=r2(gross - r2(gross * rate)), pay=next_wd(d, PAY_LAG[t])))
    return sorted(out, key=lambda x: (x["ex"], x["t"]))


def cash_flows(px):
    """托管账户 2025-05-01 至 2025-10-31 的资金流水，倒推出期初余额，使 2025-10-31 日终正好是 A01 的 1,500,000.00 美元。"""
    flows = []
    for x in hist_divs():
        flows.append((x["pay"], "股息收入", x["t"], f"现金股利（除息日 {x['ex']}，{x['sh']:,} 股 × {x['per']:.2f}）", x["gross"]))
        flows.append((x["pay"], "预提所得税", x["t"], f"代扣税款（除息日 {x['ex']}，扣缴率 {x['rate'] * 100:.0f}%）", -x["tax"]))
    d, q = LRCX_BUY
    amt = r2(q * px["LRCX"][d])
    flows.append((d, "证券买入", "LRCX", f"买入 {q:,} 股，成交价 {px['LRCX'][d]:.2f}", -amt))
    flows.append((d, "交易佣金", "LRCX", f"佣金 {OLD_COMM * 100:.2f}%", -r2(amt * OLD_COMM)))
    bad = next(x for x in hist_divs() if (x["t"], x["ex"]) == ("LRCX", LRCX_BAD))
    flows.append((LRCX_REFUND_DAY, "退税款", "LRCX", f"多扣预提税退回（除息日 {LRCX_BAD}，30% 与 10% 之差）", r2(bad["tax"] - r2(bad["gross"] * 0.10))))
    flows.append(("2025-10-31", "业绩报酬划付", "", "2025 年度业绩报酬（L1 机构甲，划至管理人收入账户）", -HIST_FEES[1][3]))
    order = {"证券买入": 0, "交易佣金": 1}
    flows.sort(key=lambda f: (f[0], order.get(f[1], 2)))
    start = r2(CASH0 - sum(f[4] for f in flows))
    bal, rows = start, []
    for f in flows:
        bal = r2(bal + f[4])
        rows.append((*f, bal))
    assert abs(bal - CASH0) < 0.005
    return start, rows


def cash_on(rows, start, d):
    b = start
    for r in rows:
        if r[0] <= d:
            b = r[5]
    return b


