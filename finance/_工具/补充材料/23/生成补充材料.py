# ---------------- B05 ADR 与 H 股价差周度跟踪导出（2026-10-09） ----------------
def b05():
    rows = []
    for a, co, h, R, lot in ALL:
        us, hk = US[a], HK[h]
        common = [d for d in us.index if d in hk.index and d in FX.index and "2025-04-01" <= d <= "2026-09-30"]
        wk = pd.Series(common, index=pd.to_datetime(common)).groupby(pd.to_datetime(common).to_period("W-FRI")).last()
        for d in wk:
            iu, ih = list(us.index).index(d), list(hk.index).index(d)
            adv_us = float(us.turnover.iloc[max(0, iu - 19):iu + 1].mean())
            adv_hk = float(hk.turnover.iloc[max(0, ih - 19):ih + 1].mean())
            prem = float(us.close[d]) * float(FX[d]) / R / float(hk.close[d]) - 1
            rows.append([d, a, co, h, R, float(us.close[d]), float(hk.close[d]), round(float(FX[d]), 4), round(prem * 100, 2),
                         round(adv_us / 1e6, 2), round(adv_hk / 1e6, 2)])
    rows.sort(key=lambda r: (r[0], r[1]))
    with open(HERE / f"{P}B05_ADR与H股价差周度跟踪导出_20261009.csv", "w", newline="", encoding="utf-8") as f:
        wr = csv.writer(f)
        wr.writerow(["周末交易日", "ADR代码", "公司", "H股代码", "ADS比率(1ADS=股)", "ADR收盘价(美元)", "H股收盘价(港元)", "美元兑港元收盘价",
                     "溢价率(%)", "ADR近20日日均成交额(百万美元)", "H股近20日日均成交额(百万港元)"])
        wr.writerows(rows)
    return rows


