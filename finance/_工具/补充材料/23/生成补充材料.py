    # 网易：美股卖出 20,000 份，港股买入
    n, R, lot = 20_000, 5, 100

    def swap(pu, ph, fx):
        amt = r2(n * pu)
        cm, sec = r2(amt * 0.0005), r2(amt * 0.0000278)
        net = r2(amt - cm - sec)
        hkd = r2(net * fx * (1 - OLD["spread"]))
        k = int(hkd // (ph * lot))
        while True:
            v = r2(k * lot * ph)
            cost = r2(v * 0.0005) + hk_stamp(v) + r2(v * 0.000027) + r2(v * 0.0000565) + r2(v * 0.0000015)
            if v + cost <= hkd:
                break
            k -= 1
        return dict(amt=amt, cm=cm, sec=sec, net=net, hkd=hkd, lots=k, sh=k * lot, v=v, cost=r2(cost), cash=r2(hkd - v - cost))
    pu_e, ph_e = float(US["NTES"].close[e]), float(HK["9999"].close[e])
