# ---------------- B02 融资利息计提与结息台账 7-9 月 ----------------
def b02() -> None:
    rows, acc = [], 0.0
    d = dt.date(2026, 7, 8)
    while d <= dt.date(2026, 9, 30):
        ds = d.isoformat()
        intr = daily_interest(ds)
        settle = ds == "2026-09-20"
        acc = r2(acc + intr)
        paid = acc if settle else ""
        after = 0.0 if settle else acc
        rows.append([ds, principal(ds), f"{RATE:.4f}", intr, "是" if settle else "否", paid, after])
        if settle:
            acc = 0.0
        d += dt.timedelta(days=1)
    with open(HERE / f"{P}B02_融资利息计提与结息台账_2026年7至9月.csv", "w", newline="", encoding="utf-8") as f:
        wr = csv.writer(f)
