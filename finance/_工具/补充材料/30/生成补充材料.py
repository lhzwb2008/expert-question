def rc(x: D) -> D:
    return x.quantize(CENT, rounding=ROUND_HALF_UP)


def fees(amt: D, rate: D):
    comm = max(D("5"), rc(amt * rate))
    stamp, trans = rc(amt * STAMP), rc(amt * TRANS)
    return comm, stamp, trans, amt - comm - stamp - trans


