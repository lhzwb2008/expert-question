def monthly_stats(nav: pd.Series) -> list[dict]:
    """逐月：月末份额净值、当月收益、当月日度最大回撤、距止损线。"""
    out = []
    peak = nav.cummax()
    for m in sorted({d[:7] for d in nav.index if d >= "2025-07-01"}):
        sm = nav[nav.index.str[:7] == m]
        before = nav[nav.index < sm.index[0]]
        base = before.iloc[-1] if len(before) else 1.0
        dd = (sm / peak[sm.index]) - 1
        out.append(dict(m=m, end=float(sm.iloc[-1]), ret=float(sm.iloc[-1] / base - 1),
                        mdd=float(dd.min()), low=float(sm.min())))
    return out


