def b06() -> None:
    """风控系统导出的 10 月逐日持仓估值（美元）。"""
    oc = oct_close()
    rows, prev = [], None
    for d in oc.index:
        mv = {t: round(HOLD[t] * float(oc[t][d]), 2) for t in HOLD}
        tot = round(sum(mv.values()) + CASH, 2)
        for t in HOLD:
            rows.append([d, t, NAME[t], HOLD[t], f"{oc[t][d]:.2f}", f"{mv[t]:.2f}", f"{mv[t] / tot * 100:.2f}", ""])
        rows.append([d, "CASH", "美元现金", "", "", f"{CASH:.2f}", f"{CASH / tot * 100:.2f}", ""])
        chg = "" if prev is None else f"{(tot / prev - 1) * 100:.4f}"
        rows.append([d, "TOTAL", "美元资产合计", "", "", f"{tot:.2f}", "100.00", chg])
        prev = tot
    with open(HERE / f"{P}B06_10月持仓估值日报（风控系统导出）.csv", "w", newline="", encoding="utf-8-sig") as f:
        wr = csv.writer(f)
        wr.writerow(["估值日", "代码", "名称", "持股数", "收盘价_USD", "市值_USD", "占美元资产(%)", "美元资产日变动(%)"])
        wr.writerows(rows)
    print(f"[B06] {len(rows)} 行，{oc.index[0]}~{oc.index[-1]}")


