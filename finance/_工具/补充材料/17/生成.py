def b03() -> None:
    """2026-10-05 按 2025 年合同原条款（美元净值、近 5 年、25%）做的 10 月持仓回撤测算。"""
    oc = oct_close()
    mv = {t: HOLD[t] * oc[t]["2026-10-01"] for t in HOLD}
    nav = sum(mv.values()) + CASH
    w = {t: mv[t] / nav for t in HOLD}
    adj = adj_prices()
    ret = adj.pct_change()
    r = ret[(ret.index > "2021-10-01") & (ret.index <= "2026-10-02")]
    rp = sum(r[t] * w[t] for t in HOLD)
    usd = pd.concat([pd.Series([1.0], index=["2021-10-01"]), (1 + rp).cumprod()])
    dd = usd / usd.cummax() - 1
    trough = dd.idxmin()
    peak = usd[:trough].idxmax()
    years = []
    for y in sorted(set(usd.index.str[:4])):
        s = usd[usd.index.str[:4] == y]
        d = s / s.cummax() - 1
        years.append([y, s.index[0], s.index[-1], round(float(d.min()) * 100, 2), d.idxmin(), round(float(s.iloc[-1]), 6)])
    pos = sum(w.values())
    assert -dd.min() < 0.25 and pos < 0.70
    print(f"[B03] 10-01 股票仓位 {pos:.4%}；美元最大回撤 {dd.min():.4%}（{peak}~{trough}），{len(r)} 个收益日")
