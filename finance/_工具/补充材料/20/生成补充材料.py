def one_note(px: pd.Series, st: str, ko, step, floor, ki, cpn):
    """单张凭证按回测口径推到敲出或到期（和 A02、排查口径同一套观察日）。"""
    days = list(px.index)
    ob = [(k, B.obs_day(days, st, k)) for k in range(B.LOCK, B.TENOR + 1)]
    mat = ob[-1][1]
    obs = {d: k for k, d in ob}
    s0, hit, first_ki = px[st], False, None
    i0 = days.index(st)
    for d in days[i0 + 1: days.index(mat) + 1]:
        c = px[d]
        if d in obs and c >= s0 * B.level(ko, step, floor, obs[d]):
            hd = (pd.Timestamp(d) - pd.Timestamp(st)).days
            return dict(type="敲出", end=d, k=obs[d], days=hd, ret=cpn * hd / 365, ki=first_ki, s0=s0, c=c)
        if c < s0 * ki and not hit:
            hit, first_ki = True, d
    hd = (pd.Timestamp(mat) - pd.Timestamp(st)).days
    ret = min(0.0, px[mat] / s0 - 1) if hit else cpn * hd / 365
    return dict(type="敲入亏损" if hit and ret < 0 else "到期未敲入", end=mat, k=24, days=hd, ret=ret, ki=first_ki, s0=s0, c=px[mat])


