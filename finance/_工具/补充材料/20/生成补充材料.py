def ref_runs(px: pd.Series, r, end: str = END_RS, first: str = "2015-01-01") -> pd.DataFrame:
    """参照结构在指数上逐日滚动：每个交易日开一张，推到敲出或到期，到期日晚于 end 的不算。"""
    _, _, ten, lock, ko, step, floor, ki = r
    px = px[px.index <= end]
    days = list(px.index)
    pos = {d: i for i, d in enumerate(days)}
    out = []
    for st in days:
        if st < first:
            continue
        ob = [(k, B.obs_day(days, st, k)) for k in range(lock, ten + 1)]
        mat = ob[-1][1]
        if mat is None:
            break
        om = {d: k for k, d in ob}
        s0, hit, res = px[st], None, None
        for d in days[pos[st] + 1: pos[mat] + 1]:
            c = px[d]
            if d in om and c >= s0 * max(floor, ko - step * (om[d] - lock)):
                res = ("敲出", d)
                break
            if hit is None and c < s0 * ki:
                hit = d
        if res is None:
            res = ("敲入亏损" if hit and px[mat] < s0 else "到期未敲入", mat)
        out.append(dict(start=st, y=st[:4], type=res[0], end=res[1], days=(pd.Timestamp(res[1]) - pd.Timestamp(st)).days,
                        ki=hit, ratio=px[mat] / s0, ki_ko=bool(hit) and res[0] == "敲出"))
    return pd.DataFrame(out)


def rvol(s: pd.Series, end: str, n: int) -> float:
    s = s[s.index < end]
    return float(s.pct_change().iloc[-n:].std() * 252 ** 0.5 * 100)


