L3_SUB = ("2026-03-16", 1.3682, 8000000.00, 5847098.38)
NAV_1031_POST = 48655990.00  # 2025-10-31 计提后资产净值，就是 24 题 A01 期初持仓按收盘价算出的期初净值
NAV_2024 = 30747603.91  # 2024-10-31 计提前资产净值（当时只有 L1）
HURDLE = 0.08
FEE = 0.20
INV = {"L1": "机构甲（某银行理财子公司）", "L2": "机构乙（某保险资管）", "L3": "机构丙（某家族办公室）"}

r2 = lambda x: round(x + 1e-9, 2)
r4 = lambda x: round(x + 1e-12, 4)
w2 = lambda x: f"{x:,.2f}"
pc = lambda x: f"{x * 100:.2f}%"


def days(a, b):
    return (dt.date.fromisoformat(b) - dt.date.fromisoformat(a)).days


def load():
    rq, q = load_mcp_prices(RAW / "QQQ_5y.json", 0)
    rn, n = load_mcp_prices(RAW / "NDX_5y.json", 0)
    lp = json.load(open(RAW / "QQQ.US_noadj.json", encoding="utf-8"))
    u = {x["date"]: float(x["close"]) for x in lp["返回"]}
    return rq, q, rn, n, lp, u


def hist():
    """原合同 8% 门槛下的两次计提，和 24 题补充材料里的 HIST_FEES 逐项复核。"""
    out = []
    u0 = L1_SUB[1]
    # 2024-10-31：L1 从申购确认日起算
    unit = r4(NAV_2024 / u0)
    hw = 1.0 * (1 + HURDLE * days(L1_SUB[0], "2024-10-31") / 365)
    ex = r4(unit - hw)
    fee = r2(ex * u0 * FEE)
    ded = r2(fee / unit)
    assert (unit, ex, fee, ded, r2(u0 - ded)) == HIST_FEES[0][1:], (unit, ex, fee, ded)
    out.append(dict(d="2024-10-31", nav=NAV_2024, units=u0, unit=unit, lots=[
        dict(k="L1", bd=L1_SUB[0], bu=1.0, n=days(L1_SUB[0], "2024-10-31"), hw=hw, ex=ex, take=True, fee=fee, ded=ded, after=r2(u0 - ded), u=u0)]))
    # 2025-10-31：L1 从 2024-10-31 起算，L2 从申购确认日起算
    u1a = HIST_FEES[0][5]
    tot = r2(u1a + L2_SUB[3])
    nav = r2(NAV_1031_POST + HIST_FEES[1][3])
    unit = r4(nav / tot)
    assert unit == 1.3520
    hw1 = 1.18 * (1 + HURDLE * days("2024-10-31", "2025-10-31") / 365)
    ex1 = r4(unit - hw1)
    fee1 = r2(ex1 * u1a * FEE)
    ded1 = r2(fee1 / unit)
    assert (ex1, fee1, ded1, r2(u1a - ded1)) == HIST_FEES[1][2:]
    hw2 = L2_SUB[1] * (1 + HURDLE * days(L2_SUB[0], "2025-10-31") / 365)
    out.append(dict(d="2025-10-31", nav=nav, units=tot, unit=unit, lots=[
        dict(k="L1", bd="2024-10-31", bu=1.18, n=365, hw=hw1, ex=ex1, take=True, fee=fee1, ded=ded1, after=r2(u1a - ded1), u=u1a),
        dict(k="L2", bd=L2_SUB[0], bu=L2_SUB[1], n=days(L2_SUB[0], "2025-10-31"), hw=hw2, ex=r4(unit - hw2), take=False, fee=0.0, ded=0.0,
             after=L2_SUB[3], u=L2_SUB[3])]))
    return out


