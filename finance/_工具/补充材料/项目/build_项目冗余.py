def r4(x):
    return None if x is None else round(float(x), 4)


def write_csv(path: Path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def fmt_numbers(n: dict, t: dict) -> dict:
    F = {}
    for k, v in n.items():
        if isinstance(v, float):
            F[k] = f"{v:.4f}"
            F[k + "_p"] = pct(v)
            F[k + "_p1"] = pct(v, 1)
        else:
            F[k] = str(v)
    F["j_jpy_start"] = f"{n['j_jpy_start']:.2f}"; F["j_jpy_end"] = f"{n['j_jpy_end']:.2f}"; F["j_jpy_max"] = f"{n['j_jpy_max']:.2f}"
    F["j_hewj_vol20"] = f"{n['j_hewj_vol20']:,.0f}"; F["j_ewj_vol20"] = f"{n['j_ewj_vol20']:,.0f}"; F["j_dxj_vol20"] = f"{n['j_dxj_vol20']:,.0f}"
    F["j_hewj_amt"] = f"{n['j_hewj_vol20'] * n['j_hewj_px'] / 1e4:,.0f}"
    F["j_ewj_amt"] = f"{n['j_ewj_vol20'] * n['j_ewj_px'] / 1e8:,.2f}"
    F["j_hewj_px"] = f"{n['j_hewj_px']:.2f}"; F["j_ewj_px"] = f"{n['j_ewj_px']:.2f}"
    F["v2_hedged_share"] = pct(n["v2_hedged_days"] / n["v2_days"], 1)
    F["v1_hedged_share"] = pct(n["v1_hedged_days"] / n["v1_days"], 1)
    for t_ in ("DIA", "IWM"):
        F[f"o_{t_}_on_mean_bp"] = f"{n[f'o_{t_}_on_mean_bp']:.2f}"
        F[f"o_{t_}_on_std_bp"] = f"{n[f'o_{t_}_on_std_bp']:.1f}"
    F["b_px0"] = f"{n['b_px0']:.2f}"; F["b_px1"] = f"{n['b_px1']:.2f}"
    F["b_adv"] = f"{n['b_adv'] / 1e4:,.0f}"
    F["b_dia_vol"] = pct(n["b_dia_vol"], 1)
    F["b_vol_ratio"] = f"{n['b_vol'] / n['b_dia_vol']:.1f}"
    for k in ("b_corr_dia", "b_corr_iwm", "b_corr_dia_12m"):
        F[k] = f"{n[k]:.2f}"
    # 2026-06-30 时点 1% 仓位的历史最差单日、最差 20 日损失（以 1 亿元组合计，万元）
    F["b_loss1_1pct"] = f"{-n['b_worst1'] * 1e8 * 0.01 / 1e4:,.1f}"
    F["b_loss20_2pct"] = f"{-n['b_worst20'] * 1e8 * 0.02 / 1e4:,.1f}"
    F["b_dd_list"] = "；".join(f"{a} 起，{b} 见底，回撤 {pct(d, 1)}，" + (f"{c} 修复" if c != "未修复" else "截至 2026-08-31 未修复")
                              for a, b, c, d in t["b_dd"])
    # 周报
    fridays, wk = t["m_weeks"]
    names = {c: nm for c, _, _, nm in UNIVERSE}
    for i in range(1, len(fridays)):
        fr = fridays[i]
        for code, vals in wk.items():
            key = code.replace("^", "").replace("=X", "").replace("-USD", "")
            p0, p1 = vals[i - 1][1], vals[i][1]
            if code == "^TNX":
                F[f"w{fr[5:7]}{fr[8:]}_{key}"] = f"{(p1 - p0) * 100:+.1f} 个基点，周末 {p1:.3f}%"
            elif code in ("JPY=X", "EURUSD=X"):
                F[f"w{fr[5:7]}{fr[8:]}_{key}"] = f"{(p1 / p0 - 1) * 100:+.2f}%，周末 {p1:.4f}"
            else:
                F[f"w{fr[5:7]}{fr[8:]}_{key}"] = f"{(p1 / p0 - 1) * 100:+.2f}%，周末 {p1:,.2f}"
    for code, rows in t["m_month"].items():
        key = code.replace("^", "").replace("=X", "").replace("-USD", "")
        for m, last, close, ret, vol, mdd, nn in rows:
            mm = m[5:]
            F[f"m{mm}_{key}_ret"] = f"{ret:+.1f} 个基点" if code == "^TNX" else f"{ret * 100:+.2f}%"
            F[f"m{mm}_{key}_vol"] = f"{vol:.1f} 个基点" if code == "^TNX" else pct(vol, 1)
            F[f"m{mm}_{key}_mdd"] = "" if mdd is None else pct(mdd, 2)
            F[f"m{mm}_{key}_close"] = f"{close:,.4f}" if code in ("JPY=X", "EURUSD=X", "^TNX") else f"{close:,.2f}"
    F["v_AMZN_dv_max"] = pct(n["v_AMZN_dv_max"], 2); F["v_TSLA_dv_max"] = pct(n["v_TSLA_dv_max"], 2)
    F["v_TSLA_maxdc"] = f"{n['v_TSLA_maxdc']:.4f}"; F["v_AMZN_maxdc"] = f"{n['v_AMZN_maxdc']:.4f}"
    return F


def render(folder: str, F: dict) -> list[Path]:
    made = []
    for src in sorted((SRC / folder).glob("*.md")):
        text = src.read_text(encoding="utf-8").format_map(F)
        if src.name.endswith(".docx.md"):
            lines = [x for x in text.splitlines()]
            title = lines[0].lstrip("# ").strip()
            blocks, head, paras = [], "", []
            for line in lines[1:]:
                if line.startswith("## "):
                    if head or paras:
                        blocks.append((head, paras))
                    head, paras = line[3:].strip(), []
                elif line.strip():
                    paras.append(line.strip())
            blocks.append((head, paras))
            dst = OUT / folder / src.name[:-3]
            bc.write_docx(dst, title, blocks)
        else:
            dst = OUT / folder / src.name
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text, encoding="utf-8")
        assert "{" not in text and "}" not in text, src
        made.append(dst)
    return made


